#!/bin/sh
# Vendors the third-party skills listed in skill-sources.txt into skills/ at
# upstream HEAD and records the commit for each in skills.lock.
# Usage: copilot/sync-skills.sh [owner/repo ...]   (default: every source)
# Review `git diff` before committing.
set -eu

here="$(cd "$(dirname "$0")" && pwd -P)"
skills="$here/skills"
lock="$here/skills.lock"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

grep -vE '^[[:space:]]*(#|$)' "$here/skill-sources.txt" > "$tmp/sources"
[ -f "$lock" ] && grep -v '^#' "$lock" > "$tmp/lock" || : > "$tmp/lock"

if [ "$#" -gt 0 ]; then
    for repo in "$@"; do
        awk -v r="$repo" '$1 == r { found = 1 } END { exit !found }' "$tmp/sources" ||
            { echo "sync-skills: '$repo' is not in skill-sources.txt" >&2; exit 1; }
    done
    printf '%s\n' "$@" | awk 'NR == FNR { want[$1] = 1; next } $1 in want' - "$tmp/sources" > "$tmp/selected"
else
    cp "$tmp/sources" "$tmp/selected"
fi

# Fetch and validate everything before touching skills/.
while read -r repo path names; do
    dir="$tmp/repos/$(echo "$repo" | tr / _)"
    git clone -q --depth 1 "https://github.com/$repo.git" "$dir"
    for name in $(echo "$names" | tr , ' '); do
        if [ ! -f "$dir/$path/$name/SKILL.md" ]; then
            echo "sync-skills: $repo has no $path/$name/SKILL.md" >&2
            exit 1
        fi
        if [ -e "$skills/$name" ] && ! awk -v r="$repo" -v n="$name" '$1 == r && $3 == n { found = 1 } END { exit !found }' "$tmp/lock"; then
            echo "sync-skills: skills/$name already exists and isn't vendored from $repo" >&2
            exit 1
        fi
    done
done < "$tmp/selected"

# Remove what the selected sources vendored last time, then copy fresh.
awk 'NR == FNR { s[$1] = 1; next } $1 in s { print $3 }' "$tmp/selected" "$tmp/lock" |
    while read -r name; do rm -rf "${skills:?}/$name"; done
awk 'NR == FNR { s[$1] = 1; next } !($1 in s)' "$tmp/selected" "$tmp/lock" > "$tmp/newlock"

mkdir -p "$skills" "$here/licenses"
while read -r repo path names; do
    dir="$tmp/repos/$(echo "$repo" | tr / _)"
    sha="$(git -C "$dir" rev-parse HEAD)"
    for name in $(echo "$names" | tr , ' '); do
        cp -R "$dir/$path/$name" "$skills/$name"
        echo "$repo $sha $name" >> "$tmp/newlock"
    done
    # Use the license closest to the skills folder (some repos license subfolders separately).
    d="$dir/$path"
    while :; do
        license="$(find "$d" -maxdepth 1 -type f -name 'LICENSE*' | head -1)"
        if [ -n "$license" ] || [ "$d" = "$dir" ]; then break; fi
        d="$(dirname "$d")"
    done
    if [ -n "$license" ]; then
        cp "$license" "$here/licenses/$(echo "$repo" | tr / _)-LICENSE"
    else
        echo "sync-skills: warning: no LICENSE found for $repo" >&2
    fi
done < "$tmp/selected"

{
    echo "# Generated by sync-skills.sh: <repo> <commit> <skill>"
    sort "$tmp/newlock"
} > "$lock"
echo "sync-skills: done. Review with: git -C \"$here\" status --short"
